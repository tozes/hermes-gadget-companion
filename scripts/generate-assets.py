#!/usr/bin/env python3
"""Generate the apps' pixel font and mascot sources from a Hermes Gadget SDK checkout.

    python3 scripts/generate-assets.py ~/dev/hermes-gadget-sdk-ble

Writes, for the iOS app, Sources/HermesCompanion/Pixel/PixelFontGlyphs.swift
(from firmware/core/src/font5x7.cpp) and
GadgetKit/Sources/GadgetKit/Pixel/MascotFrames.swift (from
firmware/core/src/mascot_data.cpp), and the same two tables for the Android
app in android/core (PixelFontGlyphs.kt and MascotFrames.kt). The glyphs stay
ASCII art so they are reviewable in a diff; the mascot bitmaps become base64
strings, which compile much faster than large byte-array literals.
"""

import base64
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONT_OUT = ROOT / "Sources" / "HermesCompanion" / "Pixel" / "PixelFontGlyphs.swift"
MASCOT_OUT = ROOT / "GadgetKit" / "Sources" / "GadgetKit" / "Pixel" / "MascotFrames.swift"
KOTLIN_DIR = ROOT / "android" / "core" / "src" / "main" / "kotlin" / "com" / "tozes" / "hermescompanion" / "core"
KOTLIN_FONT_OUT = KOTLIN_DIR / "PixelFontGlyphs.kt"
KOTLIN_MASCOT_OUT = KOTLIN_DIR / "MascotFrames.kt"


def glyph_entries(sdk: Path) -> list[tuple[str, str]]:
    """(label, rows) for the 95 glyphs, rows as seven space-separated cells."""
    src = (sdk / "firmware/core/src/font5x7.cpp").read_text()
    body = src[src.index("kGlyphs[95]") :]
    entries = re.findall(r"//\s*(.+)\n\s*((?:\"[.#]{5}\"\s*){7}),", body)
    if len(entries) != 95:
        sys.exit(f"expected 95 glyphs, found {len(entries)}")
    return [(label, " ".join(re.findall(r"\"([.#]{5})\"", rows))) for label, rows in entries]


def mascot_entries(sdk: Path) -> list[tuple[str, str, str]]:
    """(frame, size, base64) for the 12 mascot bitmaps, in source order."""
    src = (sdk / "firmware/core/src/mascot_data.cpp").read_text()
    arrays = re.findall(r"const uint8_t k(Idle|Blink|Talk)(\d+)\[(\d+)\] = \{([^}]*)\};", src)
    if len(arrays) != 12:
        sys.exit(f"expected 12 mascot bitmaps, found {len(arrays)}")
    out = []
    for frame, size, count, data in arrays:
        raw = bytes(int(b, 16) for b in re.findall(r"0x([0-9a-fA-F]{2})", data))
        if len(raw) != int(count):
            sys.exit(f"k{frame}{size}: expected {count} bytes, found {len(raw)}")
        out.append((frame, size, base64.b64encode(raw).decode()))
    return out


def kotlin_font(sdk: Path) -> str:
    lines = [
        "// Generated by scripts/generate-assets.py from the Hermes Gadget SDK's",
        "// firmware/core/src/font5x7.cpp (MIT). Do not edit.",
        "//",
        "// 5x7 glyphs for printable ASCII (0x20..0x7E). Each entry is seven rows of",
        "// five pixels, separated by spaces; '#' is an \"on\" pixel.",
        "",
        "package com.tozes.hermescompanion.core",
        "",
        "internal object PixelFontGlyphs {",
        "    val table: List<String> = listOf(",
    ]
    for label, cells in glyph_entries(sdk):
        lines.append(f"        // {label}")
        lines.append(f'        "{cells}",')
    lines += ["    )", "}", ""]
    return "\n".join(lines)


def kotlin_mascot(sdk: Path) -> str:
    lines = [
        "// Generated by scripts/generate-assets.py from the Hermes Gadget SDK's",
        "// firmware/core/src/mascot_data.cpp. Do not edit.",
        "//",
        "// Artwork: the Hermes Agent mascot (MIT License, Copyright (c) 2025 Nous Research).",
        "// See NOTICE.",
        "//",
        "// Square 1-bit bitmaps, row-major, MSB first, rows padded to whole bytes;",
        "// a set bit is ink (the white artwork). Base64-encoded.",
        "",
        "package com.tozes.hermescompanion.core",
        "",
        "internal object MascotFrames {",
        "    val encoded: List<MascotBitmapSource> = listOf(",
    ]
    for frame, size, b64 in mascot_entries(sdk):
        lines.append(f"        MascotBitmapSource(size = {size}, frame = MascotFrame.{frame.upper()}, base64 =")
        lines.append(f'            "{b64}"),')
    lines += ["    )", "}", ""]
    return "\n".join(lines)


def font(sdk: Path) -> str:
    src = (sdk / "firmware/core/src/font5x7.cpp").read_text()
    body = src[src.index("kGlyphs[95]") :]
    entries = re.findall(r"//\s*(.+)\n\s*((?:\"[.#]{5}\"\s*){7}),", body)
    if len(entries) != 95:
        sys.exit(f"expected 95 glyphs, found {len(entries)}")
    lines = [
        "// Generated by scripts/generate-assets.py from the Hermes Gadget SDK's",
        "// firmware/core/src/font5x7.cpp (MIT). Do not edit.",
        "//",
        "// 5x7 glyphs for printable ASCII (0x20...0x7E). Each entry is seven rows of",
        "// five pixels, separated by spaces; '#' is an \"on\" pixel.",
        "",
        "enum PixelFontGlyphs {",
        "    static let table: [String] = [",
    ]
    for label, rows in entries:
        cells = " ".join(re.findall(r"\"([.#]{5})\"", rows))
        lines.append(f"        // {label}")
        lines.append(f'        "{cells}",')
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def mascot(sdk: Path) -> str:
    src = (sdk / "firmware/core/src/mascot_data.cpp").read_text()
    arrays = re.findall(r"const uint8_t k(Idle|Blink|Talk)(\d+)\[(\d+)\] = \{([^}]*)\};", src)
    if len(arrays) != 12:
        sys.exit(f"expected 12 mascot bitmaps, found {len(arrays)}")
    lines = [
        "// Generated by scripts/generate-assets.py from the Hermes Gadget SDK's",
        "// firmware/core/src/mascot_data.cpp. Do not edit.",
        "//",
        "// Artwork: the Hermes Agent mascot (MIT License, Copyright (c) 2025 Nous Research).",
        "// See NOTICE.",
        "//",
        "// Square 1-bit bitmaps, row-major, MSB first, rows padded to whole bytes;",
        "// a set bit is ink (the white artwork). Base64-encoded.",
        "",
        "enum MascotFrames {",
        "    static let encoded: [MascotBitmapSource] = [",
    ]
    for frame, size, count, data in arrays:
        raw = bytes(int(b, 16) for b in re.findall(r"0x([0-9a-fA-F]{2})", data))
        if len(raw) != int(count):
            sys.exit(f"k{frame}{size}: expected {count} bytes, found {len(raw)}")
        b64 = base64.b64encode(raw).decode()
        lines.append(f"        MascotBitmapSource(size: {size}, frame: .{frame.lower()}, base64:")
        lines.append(f'            "{b64}"),')
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    sdk = Path(sys.argv[1]).expanduser()
    outputs = (
        (FONT_OUT, font(sdk)),
        (MASCOT_OUT, mascot(sdk)),
        (KOTLIN_FONT_OUT, kotlin_font(sdk)),
        (KOTLIN_MASCOT_OUT, kotlin_mascot(sdk)),
    )
    for out, text in outputs:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
        print(f"wrote {out}")


if __name__ == "__main__":
    main()
